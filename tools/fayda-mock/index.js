'use strict';

// Lambda entry point (Function URL, payload format 2.0).
const { createApp, configFromEnv } = require('./src/app');
const { dynamoStore, memoryStore } = require('./src/store');
const {
  ssmKeyProvider, memoryKeyProvider, clientJwksProvider, clientKeyProvider, ssmParamStore, fileParamStore,
} = require('./src/keys');

let handle = null;

/**
 * The RP public JWKS: CLIENT_JWKS_JSON when set, else derived from the RP private
 * key in CLIENT_KEY_PARAM (SSM, the same parameter the server signs with) or
 * CLIENT_KEY_FILE (its local stand-in), created on first use; else none.
 */
function clientJwksFrom(env, config) {
  if (config.clientJwks) return async () => config.clientJwks;
  if (env.CLIENT_KEY_FILE) return clientJwksProvider(clientKeyProvider(fileParamStore(env.CLIENT_KEY_FILE)));
  if (env.CLIENT_KEY_PARAM) {
    return clientJwksProvider(clientKeyProvider(ssmParamStore(env.CLIENT_KEY_PARAM,
      'Fayda OIDC client private key (base64 JWK). Generated by the dev Fayda mock; replace with the partner-portal key for live Fayda')));
  }
  return async () => null;
}

function buildHandler(env = process.env) {
  const config = configFromEnv(env);
  return createApp({
    config,
    store: env.CODES_TABLE ? dynamoStore(env.CODES_TABLE) : memoryStore(),
    getKey: env.SIGNING_KEY_PARAM ? ssmKeyProvider(env.SIGNING_KEY_PARAM) : memoryKeyProvider(),
    getClientJwks: clientJwksFrom(env, config),
  });
}

/** Converts a Function URL event into the app's request shape. */
function toRequest(event) {
  const headers = {};
  for (const [k, v] of Object.entries(event.headers || {})) headers[k.toLowerCase()] = v;
  const body = event.body
    ? (event.isBase64Encoded ? Buffer.from(event.body, 'base64').toString('utf8') : event.body)
    : '';
  const host = (event.requestContext && event.requestContext.domainName) || headers.host;
  return {
    method: event.requestContext.http.method,
    path: event.rawPath || '/',
    query: new URLSearchParams(event.rawQueryString || ''),
    headers,
    body,
    origin: `https://${host}`,
  };
}

exports.handler = async (event) => {
  if (!handle) handle = buildHandler();
  return handle(toRequest(event));
};

exports.toRequest = toRequest;
exports.buildHandler = buildHandler;
