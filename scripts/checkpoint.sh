#!/bin/bash
# scripts/checkpoint.sh
# Automated session handoff script for AI-assisted development
# Run this before ending a development session to update STATE.md

set -e

echo "🛑 Creating session checkpoint..."

# Check if we're in a git repository
if ! git rev-parse --is-inside-work-tree > /dev/null 2>&1; then
    echo "❌ Error: Not in a git repository"
    exit 1
fi

# Get the project root (where .git is)
PROJECT_ROOT=$(git rev-parse --show-toplevel)
STATE_FILE="$PROJECT_ROOT/STATE.md"
TASK_FILE="$PROJECT_ROOT/TASK.md"

# Create STATE.md header
cat > "$STATE_FILE" << EOF
# ⏸ STATE.md - Save Point (Token Resume)

## Purpose
This file serves as a **session checkpoint** for AI-assisted development. When token limits are reached or context needs to be preserved, this file provides the resumption point.

---

## 🛑 Session Checkpoint

**Timestamp:** $(date '+%Y-%m-%d %H:%M:%S %Z')  
**Status:** Checkpoint created by automation  
**Active Branch:** $(git branch --show-current)  

---

## 📍 Current Context

### Last Git Commits
EOF

# Add last 5 commits
git log -n 5 --pretty=format:"- %h: %s (%ar)" >> "$STATE_FILE"

# Add current task status
cat >> "$STATE_FILE" << EOF


---

## 🚧 Current Task Status

See \`TASK.md\` for detailed task breakdown.

**Incomplete Tasks:**
EOF

# Extract incomplete tasks from TASK.md (lines with [ ] or [/])
if [ -f "$TASK_FILE" ]; then
    grep -E "^- \[([ /])\]" "$TASK_FILE" | head -n 5 >> "$STATE_FILE" || echo "- No incomplete tasks found" >> "$STATE_FILE"
else
    echo "- TASK.md not found" >> "$STATE_FILE"
fi

# Add git status
cat >> "$STATE_FILE" << EOF


---

## 📦 Uncommitted Changes

EOF

if git diff --quiet && git diff --cached --quiet; then
    echo "- No uncommitted changes (working tree clean)" >> "$STATE_FILE"
else
    echo "**Modified files:**" >> "$STATE_FILE"
    git status --short >> "$STATE_FILE"
fi

# Add resumption prompt
cat >> "$STATE_FILE" << EOF


---

## ⏭️ Resumption Prompt

**For Next AI Session:**

\`\`\`
Read STATE.md and TASK.md. Continue work based on the last commit and incomplete tasks.
Current branch: $(git branch --show-current)
Last commit: $(git log -1 --pretty=format:"%s")
\`\`\`

---

## 🔗 Important File Locations

- **Constitution**: \`CLAUDE.md\`
- **Current Mission**: \`TASK.md\`
- **Standards**: \`.ai/standards.md\`
- **Tech Stack**: \`.ai/tech_stack.md\`
- **AOT Rules**: \`server/AOT_COMPLIANCE.md\`
- **Local Context**: \`docs/local_reality/README.md\`

---

## 💡 Notes for Future Self

- This is a **solo developer project** - optimize for context switching
- **Ethiopian context** is critical - always consider 3G speeds, data costs, offline usage
- Use \`scripts/checkpoint.sh\` to automate this file's updates
- Before each session end, run the checkpoint script

---

**Auto-generated by:** scripts/checkpoint.sh  
**Next Update:** Run \`./scripts/checkpoint.sh\` before ending session
EOF

echo "✅ Checkpoint created successfully!"
echo ""
echo "📄 STATE.md updated with:"
echo "   - Last 5 commits"
echo "   - Current task status"
echo "   - Uncommitted changes"
echo "   - Resumption prompt"
echo ""
echo "💡 You are safe to close the session."
echo "   Next AI session should start by reading STATE.md and TASK.md"

